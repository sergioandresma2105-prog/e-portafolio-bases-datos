SET SERVEROUTPUT ON
SET LINESIZE 200

-- ---------------------------------------------------------------------
-- 0. Comprobación: ¿en qué sesión estoy?
--    Ejecute esto en LAS DOS ventanas. Los números deben ser distintos.
-- ---------------------------------------------------------------------
SELECT USER                                   AS usuario,
       SYS_CONTEXT('USERENV','SID')           AS sid,
       SYS_CONTEXT('USERENV','SESSION_USER')  AS sesion_de
  FROM dual;

-- ---------------------------------------------------------------------
-- 1. Limpieza previa
-- ---------------------------------------------------------------------
BEGIN
  FOR t IN (SELECT table_name FROM user_tables
             WHERE table_name IN ('MOVIMIENTO','CUENTA','ASIENTO',
                                  'SILLA','TRABAJO')) LOOP
    EXECUTE IMMEDIATE 'DROP TABLE '||t.table_name||' CASCADE CONSTRAINTS PURGE';
  END LOOP;
END;
/

-- ---------------------------------------------------------------------
-- 2. Caso bancario: el clásico de las transacciones
-- ---------------------------------------------------------------------
CREATE TABLE cuenta (
  id_cuenta   NUMBER        NOT NULL,
  titular     VARCHAR2(40)  NOT NULL,
  saldo       NUMBER(14,2)  NOT NULL,
  version     NUMBER        DEFAULT 0 NOT NULL,   -- para el bloqueo optimista
  CONSTRAINT pk_cuenta PRIMARY KEY (id_cuenta),
  CONSTRAINT ck_saldo  CHECK (saldo >= 0)
);

CREATE TABLE movimiento (
  id_mov      NUMBER GENERATED BY DEFAULT AS IDENTITY,
  id_cuenta   NUMBER        NOT NULL,
  fecha_mov   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  concepto    VARCHAR2(60)  NOT NULL,
  valor       NUMBER(14,2)  NOT NULL,
  CONSTRAINT pk_movimiento PRIMARY KEY (id_mov),
  CONSTRAINT fk_mov_cuenta FOREIGN KEY (id_cuenta) REFERENCES cuenta
);
-- OJO: esta llave foránea queda SIN índice a propósito.
-- En el ejercicio 7 vamos a ver qué provoca eso.

INSERT INTO cuenta (id_cuenta, titular, saldo) VALUES (1, 'Ana Torres',   1000000);
INSERT INTO cuenta (id_cuenta, titular, saldo) VALUES (2, 'Beto Lozano',   500000);
INSERT INTO cuenta (id_cuenta, titular, saldo) VALUES (3, 'Carla Méndez',  750000);
COMMIT;

-- ---------------------------------------------------------------------
-- 3. Caso de reserva de sillas: para FOR UPDATE y SKIP LOCKED
-- ---------------------------------------------------------------------
CREATE TABLE silla (
  id_silla    NUMBER        NOT NULL,
  fila        VARCHAR2(2)   NOT NULL,
  numero      NUMBER        NOT NULL,
  estado      VARCHAR2(12)  DEFAULT 'LIBRE' NOT NULL,
  reservada_por VARCHAR2(40),
  CONSTRAINT pk_silla PRIMARY KEY (id_silla),
  CONSTRAINT ck_silla_estado CHECK (estado IN ('LIBRE','RESERVADA','VENDIDA'))
);

INSERT INTO silla (id_silla, fila, numero)
SELECT level, CHR(65 + TRUNC((level-1)/10)), MOD(level-1,10)+1
  FROM dual CONNECT BY level <= 30;
COMMIT;

-- ---------------------------------------------------------------------
-- 4. Cola de trabajos: para el demo de SKIP LOCKED
-- ---------------------------------------------------------------------
CREATE TABLE trabajo (
  id_trabajo  NUMBER        NOT NULL,
  estado      VARCHAR2(12)  DEFAULT 'PENDIENTE' NOT NULL,
  payload     VARCHAR2(60)  NOT NULL,
  procesado_por VARCHAR2(30),
  CONSTRAINT pk_trabajo PRIMARY KEY (id_trabajo)
);

INSERT INTO trabajo (id_trabajo, payload)
SELECT level, 'Tarea número '||level FROM dual CONNECT BY level <= 20;
COMMIT;

-- ---------------------------------------------------------------------
-- 5. Tabla para el demo de SAVEPOINT
-- ---------------------------------------------------------------------
CREATE TABLE asiento (
  id_asiento  NUMBER        NOT NULL,
  descripcion VARCHAR2(60)  NOT NULL,
  valor       NUMBER(14,2)  NOT NULL,
  CONSTRAINT pk_asiento PRIMARY KEY (id_asiento)
);

-- ---------------------------------------------------------------------
-- 6. Verificación
-- ---------------------------------------------------------------------
SELECT 'CUENTA' AS tabla, COUNT(*) AS filas FROM cuenta
UNION ALL SELECT 'SILLA',   COUNT(*) FROM silla
UNION ALL SELECT 'TRABAJO', COUNT(*) FROM trabajo;

SELECT id_cuenta, titular, saldo, version FROM cuenta ORDER BY id_cuenta;

